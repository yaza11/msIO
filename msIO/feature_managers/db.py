@contextmanager
def gc_paused():
    """
    Pause the cyclic garbage collector while building millions of objects (spectra, dicts of libraries): its full
    collections get longer with every object and hold the GIL, which freezes a GUI running this in a worker thread.
    """
    was_enabled: bool = gc.isenabled()
    gc.disable()
    try:
        yield
    finally:
        if was_enabled:
            gc.enable()


def eager_options_for(cls, strategy="selectin", maxdepth=10, seen=None):
    """ Build loader options to eagerly load all relationships on cls up to
    maxdepth.
    strategy: "selectin" (good default) or "joined".
    """
    if seen is None:
        seen = set()

    opts = []
    mapper = inspect(cls)
    for rel in mapper.relationships:
        # Skip if already visited this path (prevents cycles via backrefs)
        key = (mapper.class_, rel.key)
        if (key in seen) or key[1].startswith('combined'):
            continue
        seen_add = seen | {key}
        # Choose loader
        loader_fn = selectinload if strategy == "selectin" else joinedload
        loader = loader_fn(getattr(mapper.class_, rel.key))

        # Recurse into target mapper
        if maxdepth > 1:
            subopts = eager_options_for(rel.mapper.class_, strategy=strategy, maxdepth=maxdepth - 1, seen=seen_add)
            if subopts:
                loader = loader.options(*subopts)

        opts.append(loader)
    return opts


class FeatureManagerDB:
    """
    Object for accessing and modifying a DB created with a ProjectImportManager
     instance
    """
    path_file: str = None
    _mzs_sorted: np.ndarray[float] = None
    _f_ids_sorted: np.ndarray[int] = None

    def __init__(self, path_file_db: str):
        if not os.path.exists(path_file_db):
            raise FileNotFoundError(f"File {path_file_db} does not exist!")
        self.path_file: str = path_file_db

    @property
    def session_maker(self) -> 'session_maker':
        _Session = get_sessionmaker(self.path_file)
        return _Session

    def get_feature(self, feature_id: int) -> FeatureCombined:
        feature_id = int(feature_id)

        opts = eager_options_for(FeatureCombined, strategy="selectin")

        with self.session_maker() as session:
            obj = session.execute(
                select(FeatureCombined)
                .where(FeatureCombined.feature_id == feature_id)
                .options(*opts)
            ).unique().scalar_one()
        return obj

    def get_value_from_table_for_feature_id(
            self,
            feature_id: int,
            column_name: str,
            table_name: str
    ):
        with self.session_maker() as session:
            return session.execute(
                text(f"SELECT {column_name} FROM {table_name} WHERE feature_id = :feature_id"),
                {"feature_id": feature_id},
            ).scalar_one()

    def _get_all_attributes_from(self, obj) -> list:
        with self.session_maker() as session:
            attrs = session.execute(select(obj)).scalars().all()
        return attrs

    @cached_property
    def feature_ids(self) -> list[int]:
        return self._get_all_attributes_from(FeatureCombined.feature_id)

    @cached_property
    def mzs(self) -> dict[int, float]:
        return self._get_dict_for_attributes(FeatureMetaboScape, 'mz_meas')

    def get_missing_indexes(self) -> dict[str, tuple[str, str]]:
        """
        Indexes that speed up loading spectra but don't exist in the database (databases created before they were
        added to the models): {index name: (table, column)}.
        """
        missing: dict[str, tuple[str, str]] = {}
        with self.session_maker() as session:
            connection = session.connection()
            for name, (table, column) in SPECTRA_INDEXES.items():
                indexed_columns = {
                    connection.exec_driver_sql(f'PRAGMA index_info("{index[1]}")').fetchone()[2]
                    for index in connection.exec_driver_sql(f'PRAGMA index_list("{table}")').fetchall()
                }
                if column not in indexed_columns:
                    missing[name] = (table, column)
        return missing

    def create_missing_indexes(self):
        """Create the missing indexes (once per database, takes a while and some space for large libraries)."""
        with self.session_maker() as session:
            connection = session.connection()
            for name, (table, column) in self.get_missing_indexes().items():
                connection.exec_driver_sql(f'CREATE INDEX IF NOT EXISTS {name} ON "{table}" ("{column}")')
            session.commit()

    def _fetch_row_chunks(self, stmt, chunk_size: int = 50_000) -> Iterator[list[tuple]]:
        """
        Execute a select statement with the plain database cursor (SQLAlchemy's row processing is about 5 times
        slower, which matters for libraries with millions of rows) and yield the rows in chunks.

        Processing millions of rows in one C call (fetchall, dict(rows)) holds the GIL for seconds, which freezes
        a GUI running this in a worker thread, chunks give other threads a chance in between.
        """
        with self.session_maker() as session:
            connection = session.connection()
            sql = str(stmt.compile(dialect=connection.dialect, compile_kwargs={'literal_binds': True}))
            cursor = connection.connection.cursor().execute(sql)
            while chunk := cursor.fetchmany(chunk_size):
                yield chunk

    def _fetch_rows(self, stmt) -> list[tuple]:
        rows: list[tuple] = []
        for chunk in self._fetch_row_chunks(stmt):
            rows.extend(chunk)
        return rows

    def _get_dict_for_attributes(self, parent_obj, attr) -> dict:
        # one query for ids and values, so they are guaranteed to belong together
        values: dict = {}
        with gc_paused():
            for chunk in self._fetch_row_chunks(select(getattr(parent_obj, 'feature_id'), getattr(parent_obj, attr))):
                values.update(chunk)
        return values

    def get_all_attributes_from(
            self,
            parent_obj,
            attr_name: str,
            missing_value=None,
            add_missing_values: bool = False
    ) -> dict[int, Any]:
        d = self._get_dict_for_attributes(parent_obj, attr_name)
        if add_missing_values:
            missing_features = set(self.feature_ids) - set(d.keys())
            for f in missing_features:
                d[f] = missing_value
        return d

