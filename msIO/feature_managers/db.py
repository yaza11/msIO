    def get_values_for_feature(self, feature_id) -> dict[str, Any]:
        out = {}
        table_to_vals = {
            'metaboscape_features': ['rt_seconds', 'CCS', 'mz_meas', 'adduct_metaboscape', 'formula_metaboscape', 'annotation_source', 'annotation_type'],
            'compound_candidate': ['name_sirius', 'xlogp', 'inchi', 'smiles']
        }

        with self.session_maker() as session:
            for table_name, col_names in table_to_vals.items():
                out |= dict(zip(col_names, session.execute(
                    text(f"SELECT {', '.join(col_names)} FROM {table_name} WHERE feature_id = :feature_id"),
                    {"feature_id": feature_id},
                ).one()))
            return out

    def find_by_name(self, name: str, case_sensitive: bool = False, substring: bool = False) -> list[int]:
        """Return a list of feature ids with names matching the criteria."""
        t_name = lambda n: n if case_sensitive else n.lower()
        cpr_f = lambda a, b: a in b if substring else a == b
        name_l = t_name(name)
        return [f_id for f_id, name in self.names.items() if cpr_f(name_l, t_name(name))]

    def find_matches(
            self,
            mzs: Iterable[float] | dict[int, float],
            max_dmz_da: float = None,
            max_dmz_ppm: float | int = None,
            ms2_spectra: Iterable[PeakList | None] | dict[int, PeakList | None] = None,
            max_ms2_dmz_da: float = 10e-3,
            min_ms2_score: float | None = 0.7,
            metric: Callable[[PeakList | None, PeakList | None], float] | Literal['cosine_fwd', 'cosine_bwd', 'cosine_sim', 'modified_cosine_greedy'] = 'cosine_sim',
            return_nhits_ms2: bool = False,
            require_ms2: bool = False,
            progress_callback: Callable[[int, int], None] = None,
    ):
        """
        Find matches in the library for a list of provided m/z values. Optionally, also require MS2 matches.

        progress_callback(n_done, n_total) is called after scoring the matches of each m/z value (e.g. for a
        progress bar in a GUI).
        """
        assert (max_dmz_da is not None) or (max_dmz_ppm is not None), \
            'provide either max_dmz_mda or max_dmz_ppm (but not both)'
        if (as_dicts := isinstance(mzs, dict)) and (ms2_spectra is not None) and (not isinstance(ms2_spectra, dict)):
            raise ValueError('If mzs are provided as dict, ms2 must also be a dict')

        if as_dicts:
            mz_ids: list[int] = list(mzs.keys())
            mzs: list[float] = list(mzs.values())
            if ms2_spectra is not None:
                ms2_spectra: list[PeakList | None] = [ms2_spectra.get(f_id) for f_id in mz_ids]
        else:
            assert len(ms2_spectra) == len(mzs), \
                'ms2 and mzs must have the same length (can set ms2 to None for some mzs, if not available)'
            mz_ids = None

        logger.info(f'finding precursor matches')
        matched_f_ids: list[list[int]] = self.find_matches_precursor(
            mzs=mzs, max_dmz_da=max_dmz_da, max_dmz_ppm=max_dmz_ppm
        )
        logger.info(f'found matches for {sum(1 for mchs in matched_f_ids if len(mchs) > 0):_} features')

        # no ms2 spectra provided, so we can not score them
        if ms2_spectra is None:
            if as_dicts:
                out = {mz_id: matches_per_meas for mz_id, matches_per_meas in zip(mz_ids, matched_f_ids) if
                       len(matches_per_meas) > 0}
                return out
            else:
                return matched_f_ids

        if isinstance(metric, str):
            if metric == 'cosine_sim':
                metric = cosine_similarity_sym
            elif metric == 'cosine_fwd':
                metric = cosine_similarity_forward
            elif metric == 'cosine_backward':
                metric = cosine_similarity_backward
            elif metric == 'modified_cosine_greedy':
                # need to convert to matchms SpectrumType, each spectrum only once (a measured spectrum is
                # compared to all its library matches, a library spectrum to all measured features it matches)
                matchms_spectra: dict[int, Any] = {}

                def to_matchms(spectrum: PeakList, precursor_mz: float):
                    if (key := id(spectrum)) not in matchms_spectra:  # spectra stay alive during the search
                        matchms_spectra[key] = peaklist_to_spectrum(spectrum, precursor_mz=precursor_mz)
                    return matchms_spectra[key]

                def metric(a, b, max_dmz_da, return_nhits):
                    # a: library spectrum, b: measured spectrum (see call below)
                    if (a is None) or (b is None):
                        return float('nan'), 0 if return_nhits else float('nan'),
                    sim = ModifiedCosineGreedy(tolerance=max_dmz_da, intensity_power=.5)
                    sa = to_matchms(a, precursor_mz=mz_lib)
                    sb = to_matchms(b, precursor_mz=mz_meas)
                    res = sim.pair(sa, sb)
                    if return_nhits:
                        return res['score'], res['matches']
                    return res['score'],
            else:
                raise ValueError(f'Unknown metric {metric}')

        # fetch ms2 spectra of library matches
        matched_f_ids_raveled: set[int] = set()
        for _f_ids_matched_precursor in matched_f_ids:
            matched_f_ids_raveled.update(_f_ids_matched_precursor)

        logger.info(f'loading lib ms2 spectra for {len(matched_f_ids_raveled):_} features')
        matched_ms2_spectra_lib: dict[int, PeakList] = self.get_ms_spectra(list(matched_f_ids_raveled), level=2)

        ann_libs: dict[int, str] = self._get_dict_for_attributes(FeatureMetaboScape, 'annotation_type')

        # assign scores
        # ms2_scores: list[list[float]] = []
        # matched_f_ids_filtered: list[list[int]] = []
        matches: list[list[dict]] = []
        for idx, (mz_meas, ms2_measured, f_id_libs) in enumerate(tqdm(
                zip(mzs, ms2_spectra, matched_f_ids),
                desc='assigning ms2 scores',
                total=len(mzs)
        )):
            if progress_callback is not None:
                progress_callback(idx, len(mzs))
            matches_per_meas: list[dict] = []
            for f_id_lib in f_id_libs:
                mz_lib = self.mzs[f_id_lib]
                ms2_score, *n_hits_ms2 = metric(
                    matched_ms2_spectra_lib.get(f_id_lib), ms2_measured, max_ms2_dmz_da, return_nhits=return_nhits_ms2
                )
                # only add the entry if ms2 is not required or score is above the threshold
                if (require_ms2 and np.isnan(ms2_score)) or (ms2_score < min_ms2_score):
                    continue

                match: dict = dict(
                    feature_id=f_id_lib,
                    name=self.names.get(f_id_lib),
                    formula=self.formula_metaboscape.get(f_id_lib),
                    adduct=self.adduct.get(f_id_lib),
                    ms2_score=ms2_score,
                    dmz_mda= (dmz := (mz_meas - mz_lib)) * 1e3,
                    dmz_ppm= dmz / mz_lib * 1e6,
                    source_library=ann_libs.get(f_id_lib, 'unknown'),
                )
                if return_nhits_ms2:
                    match['n_hits_ms2'] = n_hits_ms2[0]
                matches_per_meas.append(match)

            matches.append(matches_per_meas)

        if progress_callback is not None:
            progress_callback(len(mzs), len(mzs))
        if as_dicts:
            out = {mz_id: matches_per_meas for mz_id, matches_per_meas in zip(mz_ids, matches) if len(matches_per_meas) > 0}
            return out
        return matches

